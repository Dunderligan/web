		<h3 class="font-display text-xl font-bold text-gray-900 dark:text-gray-100">
			7. REGELBROTT OCH STRAFF
		</h3>
		<ul class="list-inside list-disc space-y-1">
			<li>
				7.1 Skulle deltagare bryta mot regler utan tidigare specificerade straff får denna spelare
				en varning och i de fall där det är lämpligt, en avstängning under nästa match.
				<ul class="ml-4 list-inside list-disc">
					<li>
						7.1.1 Skulle samma spelare begå synnerligen allvarliga regelbrott, begå ytterligare
						regelbrott, eller försöka spela trots tillfällig avstängning, så stängs spelaren av från
						resterande del av ligan och nästkommande säsong.
					</li>
				</ul>
			</li>
