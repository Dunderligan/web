			<li>
				1.1 Deltar du i turneringen har du en skyldighet att uppföra dig, och använda sunt förnuft.
				Kort beskrivet; i Dunderligan är vi alla vänner.
			</li>
			<li>
				1.2 Toxicity, oschysst beteende, och alla former av påhopp tolereras ej. Detta gäller både i
