	<div class="space-y-3">
		<h3 class="font-display text-xl font-bold text-gray-900 dark:text-gray-100">2. DITT LAG</h3>
		<ul class="list-inside list-disc space-y-1">
			<li>
				2.1 Det är mycket viktigt att matcher spelas inom den tidsram de är tänkta att spelas.
				Matcher spelas en gång i veckan under fyra veckor i ordningen de skrivs ut i kanalen
				spelschema. Alla lag som anmäler sig förväntas lyckas boka in och spela samtliga ligamatcher
				innan grundseriens slutdatum. Samma princip gäller för slutspelsmatcherna där varje
				slutspelsrunda pågår i en vecka (d.v.s kvartsfinal vecka 1, semifinaler vecka 2).
				<ul class="ml-4 list-inside list-disc">
					<li>
						2.1.1 I extremfall kan dispens givas. Se i dessa fall till att mods är väl informerade
						om situationen.
					</li>
					<li>
						2.1.2 Om ett lag mot all förmodan inte lyckas spela sina matcher inom de givna
						tidsramarna kan laget och dess deltagare bli svartlistade och ej få delta i framtida
						upplagor av Dunderligan.
					</li>
				</ul>
			</li>
			<li>
				2.2 Varje lag måste ha minst en anmäld lagkapten. Lagkaptenen är lagets främste representant
				som ansvarar för att boka matcher och har den närmsta kontakten med ligaledningen.
			</li>
			<li>
				2.3 Varje lag ska ha en logotyp. Den behöver inte vara extremt välgjord, men ett seriöst
				försök ska ha gjorts och den ska gå att relatera till lagets namn på ett eller annat sätt.
				Logotypen ska snarast efter anmälan postas i kanalen #vår_laglogga i Dunderligans
				Discordserver.
			</li>
			<li>
				2.4 En spelare kan bara representera ett lag i en division under en pågående säsong.
				<ul class="ml-4 list-inside list-disc">
					<li>
						2.4.1 Skulle oväntade avhopp eller andra oförutsägbara problem med er spelartrupp uppstå
						så försöker vi självfallet att lösa det. Kontakta i så fall mods så de har kännedom om
						eran situation.
					</li>
				</ul>
			</li>
			<li>
				2.5 Samtliga spelare som ska tävla för ditt lag ska vara anmälda innan ligastart. För att en
				enskild spelare ska klassas som spelredo och tillgänglig för sitt lag ska denne redovisa sin
				SR enligt den angivna mallen i kanalen incheck i Dunderligans Discord. När denne gjort detta
				får den tillgång till lagets textkanal och röstchatt.
				<ul class="ml-4 list-inside list-disc">
					<li>
						2.5.1 Det är tillåtet att lägga till spelare i en anmäld spelartrupp innan
						anmälningsformuläret stänger. Kontakta isåfall en mod. Därefter och under turneringens
						gång är det inte möjligt att lägga till spelare i sin spelartrupp.
					</li>
					<li>
						2.5.2 Ett lag räknas som spelredo när minimiantalet spelare (6) redovisat sin SR för
						ligaledningen.
					</li>
					<li>
						2.5.3 En anmäld spelare som inte redovisat sin SR innan grundseriens startdatum
						betraktas som icke anmäld och är otillgänglig för spel under säsongen.
					</li>
				</ul>
			</li>
		</ul>
	</div>
	<div class="space-y-3">
		<h3 class="font-display text-xl font-bold text-gray-900 dark:text-gray-100">3. RANK OCH SR</h3>
		<ul class="list-inside list-disc space-y-1">
			<li>
				3.1 Dunderligan baseras från och med den 7:e säsongen på ett system där lagets fem högst
				rankade spelare avgör vilken division de spelar i. Divisionerna delas in av ligaledningen
				efter att alla lag är anmälda. Den SR som ska anmälas är varje spelares absoluta
				peaknotering sett över <b>alla roller</b> under de tre senaste säsongerna som spelaren haft en
				rank på minst en roll i competitive role queue.
			</li>
			<li>
				3.2 Försök till manipulation av SR är strikt förbjudet. Spelare som blir påkomna med någon
				form av SR-manipulation kommer med omedelbar verkan stängas av från resterande del av
				pågående säsong och nästkommande säsong. Upptäcks flera försök av SR-manipulation inom samma
				lag stängs alla deltagare i laget av under resterande del av pågående säsong och
				nästkommande säsong. Därefter tas ett nytt beslut om spelarna är välkomna att delta på nytt.
			</li>
		</ul>
	</div>

	<div class="space-y-3">
		<h3 class="font-display text-xl font-bold text-gray-900 dark:text-gray-100">
			4. BOKA OCH SPELA MATCHER
		</h3>
		<ul class="list-inside list-disc space-y-1">
			<li>
				4.1 I grundserien spelar varje lag fyra matcher om tre maps vardera. Varje map är värd en
				poäng. Intjänade poäng räknas till tabellen som utgör seeding inför slutspelet. Ett lag kan
				som mest ta 3 poäng i en match och som minst 0. En oavgjord karta ger inga poäng till endera
				lag.
				<ul class="ml-4 list-inside list-disc">
					<li>
						4.1.1 Om två lag i slutet av gruppspelet har lika många poäng, avgörs seeding av en rad
						tiebreakers. Dessa går att se i #format.
					</li>
				</ul>
			</li>
			<li>
				4.2 Alla lag ansvarar själva för att boka in och spela sina matcher. Det främsta ansvaret
				ligger på lagkaptenen. Lagkaptenen förväntas göra sitt yttersta för att se till att alla
				lagets matcher spelas innan deadline.
				<ul class="ml-4 list-inside list-disc">
					<li>4.2.1 Matcher bokas öppet i textkanalen #boka_matcher i discord.</li>
					<li>
						4.2.2 När en match bokas in meddelas en moderator om detta snarast så att planering
						kring eventuellt matcharrangemang och casting kan påbörjas.
					</li>
				</ul>
			</li>
			<li>
				4.3 Om oförutsedda spelaravhopp innan en match gör att ett lag inte kan starta fem spelare
				från den anmälda ordinarie spelartruppen, kan ett lag ta hjälp av en temporär inhoppare från
				ett annat deltagande lag i turneringen med liknande rank som den avhoppade spelaren från den
				ordinarie truppen.
				<ul class="ml-4 list-inside list-disc">
					<li>4.3.1 Ett lag får använda högst EN temporär inhoppare per match.</li>
					<li>
						4.3.2 Temporära inhoppare måste godkännas av någon ur modsquad.
						<ul class="ml-4 list-inside list-disc">
							<li>
								4.3.2.1 Proceduren måste upprepas varje gång denne inhoppare används av laget, även
								om den hoppat in för samma lag eller till och med samma spelare tidigare under
								turneringen.
							</li>
						</ul>
					</li>
				</ul>
			</li>
			<li>
				4.4 Alla spelare i turneringen måste spela ligamatcher på sitt anmälda konto. Inga andra
				konton än de som anmälts i anmälningsformuläret accepteras under ligamatcher.
			</li>
			<li>
				4.5 Alla matcher måste spelas på den förbestämda lobbykoden. Den finns tydligt utmärkt
				längst ner i kanalen regelboken i discord.
			</li>
			<li>
				4.6 Efter matchslut ska representanter från båda lagen rapportera matchresultat och MVP ur
				det andra laget i kanalen rapportera_resultat i discord. Detta ska ske även om matchen
				streamas.
			</li>
			<li>
				4.7 Omgångarna och varje lags motståndare finns angivna i kanalerna namngiva #spelschema för
				respektive division.
				<ul class="ml-4 list-inside list-disc">
					<li>
						4.7.1 Omgångarna spelas i ordning, med en match per vecka.
						<ul class="ml-4 list-inside list-disc">
							<li>
								4.7.1.1 Map-poolen under grundserien är förbestämd och förknippad med varje omgång.
								Vilken map-pool ditt lag spelar under vilken omgång varierar beroende på division,
								och kan ses i din divisions kanal för spelscheman.
							</li>
						</ul>
					</li>
				</ul>
			</li>
			<li>
				4.8 Om slutdatumet för en omgång nås och en match ej blivit spelad, tar ligaledningen ett
				beslut om vilket lag som varit mest drivande i att få fram en bokad match. Laget som
				ligaledningen anser har drivit diskussionen tilldelas en 3-0-seger.
				<ul class="ml-4 list-inside list-disc">
					<li>
						4.8.1 I sällsynta och specifika fall där båda lagen bedöms ha varit lika drivande i att
						få till ett matchdatum men inget passande kunnat hittas, kan dispens givas att spela
						matchen senare, så länge som det inte ställer till för nästkommande omgång.
					</li>
					<li>
						4.8.2 Anses inget lag ha varit drivande i att försöka boka in matchen så stryks den,
						inget av lagen tilldelas poäng och kan bli svartlistade från deltagande i framtida
						upplagor av turneringen.
					</li>
				</ul>
			</li>
		</ul>
	</div>
	<div class="space-y-3">
		<h3 class="font-display text-xl font-bold text-gray-900 dark:text-gray-100">5. LOBBYREGLER</h3>
		<ul class="list-inside list-disc space-y-1">
			<li>
				5.1 Alla spelare ska öppna eventuella privata profiler på begäran från motståndare eller mod
				under ligamatcher.
			</li>
			<li>
				5.2 Spelarbyten och rollbyten görs endast mellan maps. Det är inte tillåtet att byta roller
				mellan två rundor i samma map.
				<ul class="ml-4 list-inside list-disc">
					<li>
						5.2.1 Max fem spelare får befinna sig samtidigt i samma lags röstkanal under pågående
						match.
					</li>
				</ul>
			</li>
			<li>
				5.3 Det är inte tillåtet att använda glitchar och buggar för att vinna fördelar i spelet.
				<ul class="ml-4 list-inside list-disc">
					<li>
						5.3.1 Till detta hör även så kallade balance spots. Exempelvis hustak och kanter där du
						kan balansera för att exempelvis gömma dig från motståndare. Att hoppa eller glida över
						dessa spots är dock okej.
					</li>
				</ul>
			</li>
			<li>
				5.4 Från och med säsong 8 använder Dunderligan sig av Hero Bans. Hur de fungerar går att
				läsa i #format
				<ul class="ml-4 list-inside list-disc">
					<li>
						5.4.1 Skulle en spelare spela en bannad karaktär aktivt under en karta, förlorar
						spelarens lag automatiskt kartan.
					</li>
					<li>
						5.4.2 Första gången det sker får spelaren en varning, vid upprepade gånger kan det leda
						till avstängning.
					</li>
				</ul>
			</li>
			<li>
				5.5 Om ett lag inte är redo att starta första kartan 15 minuter efter planerad matchstart,
				kan motståndarna begära en walkover-vinst för just den kartan.
				<ul class="ml-4 list-inside list-disc">
					<li>
						5.5.1 Mellan kartor har lag 10 minuter på sig innan de behöver kunna starta. Är de inte
						redo kan motståndarna begära en walkover-vinst för just den kartan.
					</li>
					<li>
						5.5.2 Varje gång en walkover-vinst delas ut börjar nästa nedräkning, innan nästa karta
						kan vinnas på walkover, per 5.5.1.
					</li>
					<li>5.5.3 Lag får alltid starta kartor, även om de saknar spelare.</li>
					<li>5.5.4 En spelare som är sen får inte hoppa in under en pågående karta.</li>
				</ul>
			</li>
			<li>
				5.6 Om en spelare disconnectar pausas kartan i 5 minuter, eller tills spelaren är tillbaka.
				<ul class="ml-4 list-inside list-disc">
					<li>
						5.6.1 Om en spelare disconnectar är det enbart spelaren själv som får återansluta. Byten
						får göras först för nästkommande karta.
					</li>
					<li>
						5.6.2 Om en spelare disconnectar innan kartan startat, d.v.s. innan dörrarna i spawn
						öppnat, har de rätt att starta om och byta ut spelaren.
					</li>
					<li>5.6.3 Att kartan pausas när en spelare disconnectar får inte missbrukas.</li>
				</ul>
			</li>
		</ul>
	</div>

	<div class="space-y-3">
		<h3 class="font-display text-xl font-bold text-gray-900 dark:text-gray-100">
			6. Spectators och Streams
		</h3>
		<ul class="list-inside list-disc space-y-1">
			<li>
				6.1 Spelare på truppen som inte spelar får alltid vara spectators i lobbyn, där de enbart
				får kolla på sitt eget lag. (Gäller även coaches och manager)
				<ul class="ml-4 list-inside list-disc">
					<li>
						6.1.1 Om båda lag godkänner det får utomstående spelare vara spectators, och även kunna
						se alla.
					</li>
					<li>
						6.1.2 Spectators får aldrig skriva i chatten under pågående karta.
						<ul class="ml-4 list-inside list-disc">
							<li>
								6.1.2.1 Detta gäller även i whispers till spelare, eller att på annat sätt
								kommunicera med dem.
							</li>
						</ul>
					</li>
				</ul>
			</li>
			<li>
				6.2 Om matchen streamas och castas av Dunderligans produktion får streamers, producent,
				och/eller casters sitta i spectator.
				<ul class="ml-4 list-inside list-disc">
					<li>6.2.1 Produktion får även skriva i chatten.</li>
				</ul>
			</li>
			<li>
				6.3 Att streama sin egen POV är tillåtet. Vi rekommenderar då att streama med en fördröjning
				på minst en minut.
			</li>
			<li>
				6.4 Streamsniping och screening är förbjudet och kan diskvalificera hela lag från resterande
				del av pågående säsong.
				<ul class="ml-4 list-inside list-disc">
					<li>
						6.4.1 Spelare får inte kolla på streams, varken officiella eller inofficiella, under
						pågående kartor. Detta gäller även mellan rundor. Undantag gäller för lagkamraters POVs.
					</li>
				</ul>
			</li>
		</ul>
	</div>

